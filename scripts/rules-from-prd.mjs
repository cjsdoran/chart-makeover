#!/usr/bin/env node
// Regenerates config/rules.json from the PRD's rule tables (docs/prd.md, "Rule library").
// The PRD is the master: never edit config/rules.json by hand.
//
//   node scripts/rules-from-prd.mjs           write config/rules.json
//   node scripts/rules-from-prd.mjs --check   exit 1 if config/rules.json or the prompt rule
//                                             library has drifted from the PRD (used by the tests)
//
// Plain Node, no dependencies, so it runs before `npm install`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PRD = join(ROOT, 'docs', 'prd.md');
const OUT = join(ROOT, 'config', 'rules.json');
const PROMPT_LIBRARY = join(ROOT, 'prompts', 'shared', 'rule-library.md');

const SEVERITY_WORDS = [
  ['hard stop', 'hardStop'],
  ['major', 'major'],
  ['minor', 'minor'],
  ['suggestion', 'suggestion'],
];

// Rules the PRD lets Daniel cite outside their own stage. Each entry names the PRD text that
// grants it; the script fails if that text disappears, so a PRD change can't silently drop one.
const EXTRA_STAGES = [
  { ids: ['L11', 'D10'], stage: 1, prdText: 'the chart reading is used only to check L11 and D10' },
  { ids: ['L8', 'L11'], stage: 5, prdText: 'L8 and L11 rechecked against the planned chart' },
];

/** Severity text as written in the PRD → default severity, allowed severities, condition. */
export function parseSeverity(text) {
  const lower = text.toLowerCase();
  const found = SEVERITY_WORDS
    .map(([word, key]) => ({ key, at: lower.indexOf(word) }))
    .filter((s) => s.at >= 0)
    .sort((a, b) => a.at - b.at)
    .map((s) => s.key);
  if (!found.length) throw new Error(`No severity in "${text}"`);
  const allowed = [...new Set(found)];
  const rule = { severity: allowed[0], allowed };
  if (allowed.length > 1) rule.condition = text;
  return rule;
}

function cells(line) {
  return line.trim().replace(/^\|/, '').replace(/\|$/, '').split(' | ').map((c) => c.trim().replace(/\\&/g, '&'));
}

/** Every rule row in the PRD's five stage tables, in order. */
export function rulesFromPrd(md) {
  const start = md.indexOf('\n## Rule library');
  const end = md.indexOf('\n## Fault-and-fix library');
  if (start < 0 || end < 0) throw new Error('Rule library section not found in docs/prd.md');
  const section = md.slice(start, end);
  const parts = section.split(/\n### Stage (\d) — /).slice(1);
  const rules = [];
  for (let i = 0; i < parts.length; i += 2) {
    const stage = Number(parts[i]);
    for (const line of parts[i + 1].split('\n')) {
      if (!/^\| [LDCPF]\d{1,2} \|/.test(line)) continue;
      const [id, name, test, severityText, source] = cells(line);
      rules.push({ id, stage, name, test, severityText, source, ...parseSeverity(severityText), stages: [stage] });
    }
  }
  for (const { ids, stage, prdText } of EXTRA_STAGES) {
    if (!md.includes(prdText)) throw new Error(`PRD no longer says "${prdText}": review EXTRA_STAGES`);
    for (const id of ids) {
      const r = rules.find((x) => x.id === id);
      if (!r) throw new Error(`Rule ${id} not found`);
      if (!r.stages.includes(stage)) r.stages = [...r.stages, stage].sort();
    }
  }
  const ids = rules.map((r) => r.id);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) throw new Error(`Rule ${dup} appears twice`);
  return rules;
}

export function buildRulesFile(md) {
  const date = /^(\d{1,2} \w{3} \d{4}|\w{3} \d{1,2}, \d{4}) ·/m.exec(md)?.[1] ?? null;
  const rules = rulesFromPrd(md);
  return {
    generatedFrom: 'docs/prd.md',
    prdDate: date,
    count: rules.length,
    note: 'Generated by scripts/rules-from-prd.mjs; do not edit. stages = where Daniel may cite the rule; severity = default; allowed = what the review check accepts; condition = the PRD text that chooses between them.',
    rules,
  };
}

/** Rule rows in the prompt library must match the PRD's ID, name and severity text. */
export function checkPromptLibrary(libraryMd, rules) {
  const errors = [];
  const seen = new Set();
  for (const line of libraryMd.split('\n')) {
    if (!/^\| [LDCPF]\d{1,2} \|/.test(line)) continue;
    const [id, name, , severityText] = cells(line);
    seen.add(id);
    const r = rules.find((x) => x.id === id);
    if (!r) errors.push(`${id} is in the prompt library but not in the PRD`);
    else if (r.name !== name || r.severityText !== severityText) errors.push(`${id} differs from the PRD (name or severity)`);
  }
  for (const r of rules) if (!seen.has(r.id)) errors.push(`${r.id} is missing from the prompt library`);
  return errors;
}

function main() {
  const md = readFileSync(PRD, 'utf8');
  const file = buildRulesFile(md);
  const text = `${JSON.stringify(file, null, 2)}\n`;
  if (process.argv.includes('--check')) {
    const errors = [];
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { errors.push('config/rules.json is missing'); }
    if (current && current !== text) errors.push('config/rules.json differs from docs/prd.md: run node scripts/rules-from-prd.mjs');
    errors.push(...checkPromptLibrary(readFileSync(PROMPT_LIBRARY, 'utf8'), file.rules));
    if (errors.length) {
      console.error(errors.join('\n'));
      process.exit(1);
    }
    console.log(`OK: ${file.count} rules match docs/prd.md`);
    return;
  }
  writeFileSync(OUT, text);
  console.log(`Wrote config/rules.json: ${file.count} rules from docs/prd.md (${file.prdDate})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
